#!/usr/bin/env python3
"""Fast private GUI lane: modern map reaches real 4 KiB data and refuses unrecorded views."""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import time
import re
import math
import select
from PIL import Image

p = argparse.ArgumentParser()
p.add_argument('--binary')
p.add_argument('--evidence', action='store_true', help='periodic replay animation and live Node performance evidence')
p.add_argument('--node', default='node')
p.add_argument('--animation-only', action='store_true', help='with --evidence, capture replay frames without repeating live measurements')
a = p.parse_args()
if a.animation_only and not a.evidence:
    p.error("--animation-only requires --evidence")
root = Path(__file__).resolve().parents[1]
os.chdir(root)
os.umask(0o022)
work = root / '.work' / ('input-mmod-' + str(time.time_ns())[-8:])
work.mkdir(parents=True)
for name in ('tmp', 'cache'):
    (work / name).mkdir()
spec = importlib.util.spec_from_file_location('private_input', root / 'tests/helpers/input.py')
h = importlib.util.module_from_spec(spec)
spec.loader.exec_module(h)
h.WORK = str(work)
for xml, stem in ((h.VPTR, 'virtual-pointer'), (h.VKBD, 'virtual-keyboard')):
    subprocess.run(['wayland-scanner', 'client-header', xml, str(work / (stem + '.h'))], check=True)
    subprocess.run(['wayland-scanner', 'private-code', xml, str(work / (stem + '.c'))], check=True)
h.HELPER = str(work / 'vinput')
subprocess.run(['cc', '-I', str(work), 'tests/helpers/vinput.c', str(work / 'virtual-pointer.c'),
                str(work / 'virtual-keyboard.c'), '-lwayland-client', '-lxkbcommon', '-lm', '-o', h.HELPER], check=True)
base, replay = work / 'base.jsonl', work / 'replay.jsonl'
subprocess.run(['python3', '-B', 'tests/fixtures/overview-synth.py', str(base), '--frames', '6'], check=True)
subprocess.run(['python3', '-B', 'tests/fixtures/memmap-synth.py', str(base), str(replay), '--viewports'], check=True)
os.environ['XODB_OVERVIEW_LAYOUT'] = '1'
started = time.monotonic()
checks = []
d = None
evidence = {}

def until(fn, name):
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        if not d.alive():
            raise AssertionError(d.tail())
        if fn():
            checks.append(name)
            print('PASS ' + name, flush=True)
            return
        time.sleep(.025)
    raise AssertionError(name + ': ' + d.tail())

def shot(name):
    with Image.open(d.shot(name)) as im:
        return im.convert('RGB')

def send(*cmd):
    if d.keys(*cmd, wait=False).wait(timeout=10):
        raise AssertionError('private input failed')

def field():
    lines = [line for line in Path(d.log).read_text().splitlines() if 'xodb: memmap deep x=' in line]
    if not lines:
        return None
    parts = dict(re.findall(r'(\w+)=([^ ]+)', lines[-1]))
    return {k: float(v) if k in ('x', 'y', 'pitch') else int(v, 0) for k, v in parts.items() if k in ('x', 'y', 'pitch', 'cols', 'rows', 'origin', 'cell', 'count', 'pending', 'unknown', 'collapsed', 'split', 'changed', 'nav', 'pulse')}

def point(address):
    f = field()
    i = (address - f['origin']) // f['cell']
    assert 0 <= i < f['count'], (address, f)
    return (int(f['x'] + (i % f['cols'] + .5) * f['pitch']),
            int(f['y'] + (i // f['cols'] + .5) * f['pitch']))

def snapshot(pid):
    fields = Path(f'/proc/{pid}/stat').read_text().rsplit(')', 1)[1].split()
    status = Path(f'/proc/{pid}/status').read_text()
    return dict(cpu_seconds=(int(fields[11])+int(fields[12]))/os.sysconf('SC_CLK_TCK'),
                rss_kib=int(re.search(r'VmRSS:\s+(\d+)', status).group(1)))

def periodic():
    global d
    # Every frame's explicit viewport is generated by the same page-state oracle
    # as its compact map, including the actual previous-sample change flags.
    spec = importlib.util.spec_from_file_location('memory_fixture', root / 'tests/fixtures/memmap-synth.py')
    fx = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fx)
    frames = [json.loads(line) for line in base.read_text().splitlines()][:3]
    animation = work / 'animation.jsonl'
    with animation.open('w') as out:
        for i, frame in enumerate(frames):
            mm = fx.memory_map(i, len(frames), 'process')
            tags = [v['tag'] for v in fx.vmas_layout()]
            frame['memory_map'] = mm
            frame['memory_viewports'] = [fx.viewport(mm['vmas'], tags, i, len(frames), 'process', 128*1024, ARENA, 65536, mm)]
            out.write(json.dumps(frame, separators=(',', ':'))+'\n')
    d = h.Display(str(root), ['--overview', '--look', 'modern', '--panel', 'memory_map', '--redact',
                  '--pause', '--interval-ms', '2000', '--replay', str(animation)], stdio=False, trace=False, binary=a.binary, output_size=(1280,720))
    until(lambda: field() and field()['collapsed'] > 0, 'animation replay contains measured THP collapses')
    send('tap', 25)  # play the recorded samples
    until(lambda: 'modern sample=1001 ' in Path(d.log).read_text(), 'animation reaches the preceding recorded sample')
    mark = len(Path(d.log).read_text())
    until(lambda: 'modern sample=1002 ' in Path(d.log).read_text()[mark:], 'animation reaches the changed recorded sample')
    # The two-second publication interval keeps the sequence in this sample;
    # each capture also verifies the actual sample identity below.
    captures = []
    changing = next(c['start'] for c in frame['memory_viewports'][0]['cells'] if c.get('collapsed'))
    pixel_at = point(changing)
    colors = []
    for i in range(8):
        at = time.monotonic()
        path = d.shot(f'collapse-{i:02d}')
        sample = re.findall(r'modern sample=(\d+) ', Path(d.log).read_text())[-1]
        if sample != '1002':
            raise AssertionError(('frame sequence crossed into another sample', sample))
        captures.append(dict(path=str(Path(path).relative_to(root)), monotonic=at))
        with Image.open(path) as im:
            colors.append(im.convert('RGB').getpixel(pixel_at))
    if len(set(colors)) < 2:
        raise AssertionError(('measured collapse did not animate its cell pixels', pixel_at, colors))
    checks.append('measured collapse changes its rendered cell over the frame sequence')
    evidence['collapse_pixel'] = dict(xy=pixel_at, colors=colors)
    evidence['collapse_frames'] = captures
    evidence['animation_log'] = str(Path(d.log).relative_to(root))
    d.close()
    d = None
    if a.animation_only:
        return
    # A large owned V8 process, with committed anonymous storage and periodically
    # touched pages. Nothing attaches to or enumerates a user's application.
    script = work / 'large.js'
    script.write_text("const blocks = Array.from({length: 16}, () => Buffer.alloc(32*1024*1024, 0x5a));\n"
                      "console.log('ready'); let n=0; setInterval(() => { const b=blocks[n++%blocks.length]; b[(n*4096)%b.length]^=1; }, 50);\n")
    target = subprocess.Popen([a.node, str(script)], stdout=subprocess.PIPE, stderr=open(work/'node.log','wb'))
    try:
        ready, _, _ = select.select([target.stdout], [], [], 20)
        if not ready or target.stdout.readline().strip() != b'ready':
            raise AssertionError('owned Node fixture did not become ready')
        evidence['target'] = snapshot(target.pid)
        perf = []
        os.environ['XODB_MEMMAP_PERF'] = '1'
        for size in ((1920,1080), (3840,2160)):
            for continuous in (False, True):
                d = h.Display(str(root), ['--overview', '--look', 'modern', '--panel', 'memory_map', '--redact',
                              '--memmap-pid', str(target.pid), *(['--frames','100000'] if continuous else [])],
                              stdio=False, trace=False, binary=a.binary, output_size=size)
                until(lambda: field() and field()['count'] > 10000 and field()['pending'] == 0,
                      f'live owned Node viewport is sampled at {size}')
                before = snapshot(d.app.pid)
                t0 = time.monotonic()
                peak = before['rss_kib']
                mark = len(Path(d.log).read_text())
                # This is a measurement window, never a timing pass/fail threshold.
                while time.monotonic() - t0 < 6:
                    if not d.alive():
                        raise AssertionError(d.tail())
                    peak = max(peak, snapshot(d.app.pid)['rss_kib'])
                    time.sleep(.1)
                after = snapshot(d.app.pid)
                peak = max(peak, after['rss_kib'])
                elapsed = time.monotonic() - t0
                load = os.getloadavg()
                lines = [line for line in Path(d.log).read_text()[mark:].splitlines() if 'memmap perf ' in line]
                if not lines:
                    raise AssertionError('no frame cost evidence produced')
                shot(f'live-{size[0]}-{int(continuous)}')
                perf.append(dict(size=size, continuous=continuous, seconds=elapsed,
                                 cpu_pct=100*(after['cpu_seconds']-before['cpu_seconds'])/elapsed,
                                 before=before, after=after, peak_rss_kib=peak, field=field(), load=load,
                                 measurable=load[0] <= len(os.sched_getaffinity(0)), frames=lines,
                                 log=str(Path(d.log).relative_to(root))))
                d.close()
                d = None
        evidence['performance'] = perf
    finally:
        if target.poll() is None:
            target.terminate()
        try:
            target.wait(timeout=5)
        except subprocess.TimeoutExpired:
            target.kill()
            target.wait()

ARENA = 0x7f3a00000000
SPLIT = ARENA + 74 * (1 << 20)
try:
    d = h.Display(str(root), ['--overview', '--look', 'modern', '--panel', 'memory_map',
                  '--pause', '--redact', '--replay', str(replay)], stdio=False, trace=False,
                  binary=a.binary, output_size=(1280, 720))
    until(lambda: field() and field()['pending'] == 0 and field()['count'] > 10000,
          'modern view draws a dense recorded viewport')
    f = field()
    assert f['count'] <= 65536 and all(f[k] > 0 for k in ('unknown', 'collapsed', 'split', 'changed')), f
    until(lambda: 'history=6 ' in Path(d.log).read_text(), 'paused replay preloads six actual VMA history samples')
    shot('modern-fit')
    x, y = point(SPLIT)
    for _ in range(int(math.log2(f['cell'] // 4096))):
        expected = field()['cell'] // 2
        send('scroll', x, y, -1)
        until(lambda: field()['cell'] == expected and field().get('nav') == 0,
              f'zoom geometry settles at {expected} bytes per cell')
    until(lambda: field()['cell'] == 4096 and field()['pending'] == 0,
          'pointer-anchored wheel zoom reaches recorded 4 KiB pages')
    send('m', *point(SPLIT))
    until(lambda: 'split' in Path(d.log).read_text().split('xodb: memmap deep detail ')[-1].lower(),
          '4 KiB hover reports the real split')
    shot('modern-pages')
    # The adjacent 8 KiB zoom was deliberately omitted by the replay oracle.
    send('tap', 12)  # minus
    until(lambda: field()['cell'] == 8192 and field()['pending'] == field()['count'],
          'unrecorded 8 KiB viewport stays entirely pending')
    shot('modern-pending')
    send('tap', 13)  # equals
    until(lambda: field()['cell'] == 4096 and field()['pending'] == 0,
          'returning to recorded pages restores measured states')
    # Panning only changes the viewport, not the snapshot's cell identities.
    before = field()['origin']
    send('tap', 108)
    until(lambda: field()['origin'] > before, 'arrow key pans the modern viewport')
    until(lambda: field().get('nav') == 0, 'pan geometry settles')
    shot('modern-pan')
    bad = [line for line in Path(d.log).read_text().splitlines() if 'xodb: overview layout ' in line and 'overlaps=0 ' not in line]
    if bad:
        raise AssertionError(bad[:3])
    checks.append('modern labels do not overlap')
    send('tap', 33)  # f: modern fit leaves 0 available to the global panel shortcut
    until(lambda: field()['cell'] == f['cell'] and field().get('nav') == 0, 'f fits the modern process view')
    mark = len(Path(d.log).read_text())
    send('tap', 11)  # 0: System Info
    until(lambda: 'panel=system ' in Path(d.log).read_text()[mark:], '0 still opens System Info')
    mark = len(Path(d.log).read_text())
    send('tap', 50)  # m: return to Memory Map
    until(lambda: 'history=1 ' in Path(d.log).read_text()[mark:], 'leaving the panel releases VMA history')
    text = Path(d.log).read_text()
    if any(x in text for x in ('panic:', 'Draw failed', 'frame failed')):
        raise AssertionError(text[-2000:])
    d.close()
    d = None
    if a.evidence:
        periodic()
finally:
    if d:
        d.close()
    (work / 'results.json').write_text(json.dumps(dict(checks=checks,seconds=time.monotonic()-started,evidence=evidence),indent=2)+'\n')
    print(work, flush=True)
